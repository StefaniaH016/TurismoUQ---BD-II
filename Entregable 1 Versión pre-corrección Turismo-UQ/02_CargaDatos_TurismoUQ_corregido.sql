------------------------------ 6 - TARIFA ---------------------------------------
-- Generación de 2.400 tarifas (400 habitaciones x 6 temporadas)

DECLARE
    v_precio_base NUMBER;
    v_factor NUMBER;
BEGIN
    FOR r_hab IN (SELECT id_habitacion, tipo FROM habitacion) LOOP
        v_precio_base := CASE r_hab.tipo
            WHEN 'SENCILLA' THEN 80000
            WHEN 'DOBLE'    THEN 140000
            WHEN 'SUITE'    THEN 250000
            WHEN 'CABANA'   THEN 380000
        END;

        FOR r_temp IN (SELECT id_temporada, nivel FROM temporada) LOOP
            v_factor := CASE r_temp.nivel
                WHEN 'BAJA'  THEN 1.0
                WHEN 'MEDIA' THEN 1.3
                WHEN 'ALTA'  THEN 1.7
            END;

            INSERT INTO tarifa (id_habitacion, id_temporada, valor_noche)
            VALUES (
                r_hab.id_habitacion,
                r_temp.id_temporada,
                ROUND(v_precio_base * v_factor * DBMS_RANDOM.VALUE(0.95, 1.10), -3)
            );
        END LOOP;
    END LOOP;
    COMMIT;
END;
