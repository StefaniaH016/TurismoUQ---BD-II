------------------------------- 4 - HABITACION ----------------------------------
-- Carga de 400 habitaciones garantizando que TODOS los alojamientos tengan al menos una

DECLARE
    v_hab_count NUMBER := 0;
    v_hab_por_aloj NUMBER;
    v_tipo_hab VARCHAR2(10);
    v_capacidad NUMBER;
    TYPE t_tipos IS TABLE OF VARCHAR2(10);
    v_tipos t_tipos := t_tipos('SENCILLA', 'DOBLE', 'SUITE', 'CABANA');
BEGIN
    FOR r_aloj IN (SELECT id_alojamiento, id_tipo_alojamiento FROM alojamiento ORDER BY id_alojamiento) LOOP
        v_hab_count := v_hab_count + 1;
        v_tipo_hab := v_tipos(TRUNC(DBMS_RANDOM.VALUE(1, 5)));
        v_capacidad := CASE v_tipo_hab
            WHEN 'SENCILLA' THEN 1
            WHEN 'DOBLE'    THEN 2
            WHEN 'SUITE'    THEN 4
            WHEN 'CABANA'   THEN 8
        END;

        INSERT INTO habitacion (id_alojamiento, numero, capacidad_max, tipo, descripcion)
        VALUES (
            r_aloj.id_alojamiento,
            101,
            v_capacidad,
            v_tipo_hab,
            'Habitación principal ' || LOWER(v_tipo_hab)
        );
    END LOOP;

    FOR r_aloj IN (SELECT id_alojamiento, id_tipo_alojamiento FROM alojamiento ORDER BY id_alojamiento) LOOP
        IF r_aloj.id_tipo_alojamiento = 2 THEN    
            v_hab_por_aloj := TRUNC(DBMS_RANDOM.VALUE(30, 41));
        ELSIF r_aloj.id_tipo_alojamiento = 1 THEN  
            v_hab_por_aloj := TRUNC(DBMS_RANDOM.VALUE(2, 5));
        ELSE
            v_hab_por_aloj := TRUNC(DBMS_RANDOM.VALUE(3, 8));
        END IF;

        FOR h IN 2..v_hab_por_aloj LOOP
            EXIT WHEN v_hab_count >= 400;
            v_hab_count := v_hab_count + 1;
            v_tipo_hab := v_tipos(TRUNC(DBMS_RANDOM.VALUE(1, 5)));
            v_capacidad := CASE v_tipo_hab
                WHEN 'SENCILLA' THEN 1
                WHEN 'DOBLE'    THEN 2
                WHEN 'SUITE'    THEN 4
                WHEN 'CABANA'   THEN 8
            END;

            INSERT INTO habitacion (id_alojamiento, numero, capacidad_max, tipo, descripcion)
            VALUES (
                r_aloj.id_alojamiento,
                100 + h,
                v_capacidad,
                v_tipo_hab,
                'Habitación acomodación ' || LOWER(v_tipo_hab) || ' confort'
            );
        END LOOP;
        EXIT WHEN v_hab_count >= 400;
    END LOOP;

    WHILE v_hab_count < 400 LOOP
        v_hab_count := v_hab_count + 1;
        INSERT INTO habitacion (id_alojamiento, numero, capacidad_max, tipo, descripcion)
        VALUES (1, 500 + v_hab_count, 2, 'DOBLE', 'Habitación adicional de expansión');
    END LOOP;

    COMMIT;
END;
