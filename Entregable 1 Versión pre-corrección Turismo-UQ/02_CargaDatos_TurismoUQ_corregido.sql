------------------------------ 12 - PAGO ----------------------------------------
-- Carga de los pagos para cada reserva realizada

DECLARE
    TYPE t_metodos IS TABLE OF VARCHAR2(20);
    v_metodos t_metodos := t_metodos('TARJETA_CREDITO', 'TARJETA_DEBITO', 'PSE', 'TRANSFERENCIA', 'EFECTIVO');
    
    v_total_estadia   NUMBER;
    v_total_servicios NUMBER;
    v_monto_total     NUMBER;
    v_estado_pago     VARCHAR2(12);
BEGIN
    FOR r_res IN (SELECT id_reserva, estado, fecha_creacion FROM reserva) LOOP
        
        SELECT NVL(SUM(valor_noche), 0)
        INTO   v_total_estadia
        FROM   v_noche_ocupada
        WHERE  id_reserva = r_res.id_reserva;

        SELECT NVL(SUM(cantidad * precio_unitario), 0)
        INTO   v_total_servicios
        FROM   reserva_servicio
        WHERE  id_reserva = r_res.id_reserva;

        v_monto_total := v_total_estadia + v_total_servicios;

        IF v_monto_total = 0 THEN
            v_monto_total := ROUND(DBMS_RANDOM.VALUE(180000, 500000), -3);
        END IF;

        CASE r_res.estado
            WHEN 'COMPLETADA' THEN v_estado_pago := 'EXITOSO';
            WHEN 'CONFIRMADA' THEN v_estado_pago := 'EXITOSO';
            WHEN 'CANCELADA'  THEN v_estado_pago := 'REEMBOLSADO';
            WHEN 'PENDIENTE'  THEN v_estado_pago := 'PENDIENTE';
        END CASE;

        INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
        VALUES (
            r_res.id_reserva,
            r_res.fecha_creacion,
            v_monto_total,
            v_metodos(TRUNC(DBMS_RANDOM.VALUE(1, 6))),
            v_estado_pago
        );

        IF r_res.estado = 'COMPLETADA' AND MOD(r_res.id_reserva, 5) = 0 THEN
            INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
            VALUES (
                r_res.id_reserva,
                r_res.fecha_creacion + 1,
                50000,
                'EFECTIVO',
                'EXITOSO'
            );
        END IF;

        IF MOD(r_res.id_reserva, 3000) = 0 THEN
            COMMIT;
        END IF;
    END LOOP;
    COMMIT;
END;
