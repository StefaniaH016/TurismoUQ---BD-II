------------------------------ 12 - PAGO ----------------------------------------
-- Carga de los pagos para cada reserva realizada
-- El monto es el valor de las noches (tarifa de cada día) más los servicios.
-- Pago único o anticipo del 30 % + saldo del 70 % al llegar.
-- Canceladas: reembolso del 80 % solo si se canceló con más de 5 días.

DECLARE
    TYPE t_txt IS TABLE OF VARCHAR2(20);
    v_metodos t_txt := t_txt('TARJETA_CREDITO', 'TARJETA_DEBITO', 'PSE', 'TRANSFERENCIA', 'EFECTIVO');
    c_corte  CONSTANT DATE := DATE '2026-10-01';
    v_anticipo NUMBER;
    v_saldo    NUMBER;
    v_cont     PLS_INTEGER := 0;
    v_metodo1  VARCHAR2(20);   -- método del primer pago
    v_metodo2  VARCHAR2(20);   -- método del saldo
BEGIN
    FOR r IN (
        WITH noches AS (
            SELECT rh.id_reserva, tf.valor_noche
              FROM reserva_habitacion rh
              JOIN (SELECT LEVEL - 1 AS n FROM dual CONNECT BY LEVEL <= 60) s
                ON s.n < rh.fecha_out - rh.fecha_in
              JOIN temporada t ON rh.fecha_in + s.n BETWEEN t.fecha_inicio AND t.fecha_fin
              JOIN tarifa   tf ON tf.id_habitacion = rh.id_habitacion
                              AND tf.id_temporada  = t.id_temporada
        ),
        estadia AS (
            SELECT id_reserva, SUM(valor_noche) AS total_estadia
              FROM noches
             GROUP BY id_reserva
        ),
        servicios AS (
            SELECT id_reserva, SUM(cantidad * precio_unitario) AS total_servicios
              FROM reserva_servicio
             GROUP BY id_reserva
        )
        SELECT r.id_reserva, r.estado, r.fecha_creacion, r.fecha_checkin, r.fecha_cancelacion,
               NVL(e.total_estadia, 0) + NVL(s.total_servicios, 0) AS total
          FROM reserva r
          LEFT JOIN estadia   e ON e.id_reserva = r.id_reserva
          LEFT JOIN servicios s ON s.id_reserva = r.id_reserva
         ORDER BY r.id_reserva) LOOP

        v_anticipo := ROUND(r.total * 0.3);
        v_saldo    := r.total - v_anticipo;

        -- Métodos de pago al azar
        v_metodo1 := v_metodos(TRUNC(DBMS_RANDOM.VALUE(1, 6)));
        v_metodo2 := v_metodos(TRUNC(DBMS_RANDOM.VALUE(1, 6)));

        -- Completadas y confirmadas en curso: pago total (único o anticipo + saldo)
        IF r.estado = 'COMPLETADA'
           OR (r.estado = 'CONFIRMADA' AND r.fecha_checkin < c_corte) THEN

            -- Algunos tienen antes un intento fallido
            IF DBMS_RANDOM.VALUE < 0.05 THEN
                INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
                VALUES (r.id_reserva, r.fecha_creacion, v_anticipo, 'TARJETA_CREDITO', 'FALLIDO');
            END IF;

            IF DBMS_RANDOM.VALUE < 0.40 THEN
                INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
                VALUES (r.id_reserva, r.fecha_creacion, r.total, v_metodo1, 'EXITOSO');
            ELSE
                INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
                VALUES (r.id_reserva, r.fecha_creacion, v_anticipo, v_metodo1, 'EXITOSO');
                INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
                VALUES (r.id_reserva, r.fecha_checkin, v_saldo, v_metodo2, 'EXITOSO');
            END IF;

        -- Confirmadas futuras: pago total o solo el anticipo
        ELSIF r.estado = 'CONFIRMADA' THEN
            IF DBMS_RANDOM.VALUE < 0.50 THEN
                INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
                VALUES (r.id_reserva, r.fecha_creacion, r.total, v_metodo1, 'EXITOSO');
            ELSE
                INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
                VALUES (r.id_reserva, r.fecha_creacion, v_anticipo, v_metodo1, 'EXITOSO');
            END IF;

        -- Pendientes: anticipo pendiente
        ELSIF r.estado = 'PENDIENTE' THEN
            INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
            VALUES (r.id_reserva, r.fecha_creacion, v_anticipo, v_metodo1, 'PENDIENTE');

        -- Canceladas: anticipo pagado y reembolso del 80 % si fue con más de 5 días
        ELSE
            INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
            VALUES (r.id_reserva, r.fecha_creacion, v_anticipo, v_metodo1, 'EXITOSO');

            IF r.fecha_checkin - r.fecha_cancelacion > 5 THEN
                INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
                VALUES (r.id_reserva, r.fecha_cancelacion, ROUND(v_anticipo * 0.8),
                        'TRANSFERENCIA', 'REEMBOLSADO');
            END IF;
        END IF;

        v_cont := v_cont + 1;
        IF MOD(v_cont, 5000) = 0 THEN
            COMMIT;
        END IF;
    END LOOP;
    COMMIT;
END;
/

------------------------------ 13 - RESENA --------------------------------------
-- Carga de las reseñas registradas sobre las reservas completadas
-- Cerca del 55 % deja reseña y la calificación depende de las estrellas del alojamiento

DECLARE
    TYPE t_txt IS TABLE OF VARCHAR2(200);
    v_malos   t_txt := t_txt('La habitación no estaba limpia al llegar.',
                             'No correspondió a lo que mostraban las fotos.',
                             'El servicio fue demorado y poco amable.');
    v_medios  t_txt := t_txt('Aceptable, aunque hay cosas por mejorar.',
                             'Buen lugar, pero algo aislado y sin buena señal.',
                             'Cómodo, pero el desayuno podría ser mejor.');
    v_buenos  t_txt := t_txt('Excelente atención, volvería sin duda.',
                             'Experiencia inolvidable en el Quindío, muy recomendado.',
                             'Hermosa vista y un café delicioso.',
                             'Muy buen servicio y personal amable.');
    c_corte   CONSTANT DATE := DATE '2026-10-01';
    v_calif   NUMBER;
    v_coment  VARCHAR2(200);
    v_fecha   DATE;
    v_cont    PLS_INTEGER := 0;
BEGIN
    FOR r IN (SELECT re.id_reserva, re.fecha_checkout, a.estrellas
                FROM reserva re
                JOIN alojamiento a ON a.id_alojamiento = re.id_alojamiento
               WHERE re.estado = 'COMPLETADA'
               ORDER BY re.id_reserva) LOOP

        IF DBMS_RANDOM.VALUE < 0.55 THEN
            v_calif := ROUND(1.8 + 0.6 * r.estrellas + DBMS_RANDOM.NORMAL * 0.8);
            v_calif := LEAST(5, GREATEST(1, v_calif));

            IF DBMS_RANDOM.VALUE < 0.20 THEN
                v_coment := NULL;
            ELSIF v_calif <= 2 THEN
                v_coment := v_malos(TRUNC(DBMS_RANDOM.VALUE(1, v_malos.COUNT + 1)));
            ELSIF v_calif = 3 THEN
                v_coment := v_medios(TRUNC(DBMS_RANDOM.VALUE(1, v_medios.COUNT + 1)));
            ELSE
                v_coment := v_buenos(TRUNC(DBMS_RANDOM.VALUE(1, v_buenos.COUNT + 1)));
            END IF;

            -- Reseña de 1 a 10 días después de salir, sin pasar la fecha de corte
            v_fecha := LEAST(r.fecha_checkout + TRUNC(DBMS_RANDOM.VALUE(1, 11)), c_corte);

            INSERT INTO resena (id_reserva, calificacion, comentario, fecha_resena)
            VALUES (r.id_reserva, v_calif, v_coment, v_fecha);

            v_cont := v_cont + 1;
            IF MOD(v_cont, 2000) = 0 THEN
                COMMIT;
            END IF;
        END IF;
    END LOOP;
    COMMIT;
END;
