------------------------------ 8 - RESERVA --------------------------------------
-- Carga de 25.000 reservas y asignación en RESERVA_HABITACION
-- El 55 % cae en temporada alta, 30 % en media y 15 % en baja
-- Antes de asignar una habitación se revisa que esté libre en esas fechas

DECLARE
    c_corte CONSTANT DATE := DATE '2026-10-01';
    c_fin   CONSTANT DATE := DATE '2026-12-31';

    TYPE t_num   IS TABLE OF NUMBER  INDEX BY PLS_INTEGER;
    TYPE t_fecha IS TABLE OF DATE    INDEX BY PLS_INTEGER;
    TYPE t_ocup  IS TABLE OF BOOLEAN INDEX BY VARCHAR2(30);

    v_hab_id   t_num;      -- habitaciones ordenadas por alojamiento
    v_hab_aloj t_num;
    v_hab_cap  t_num;
    v_aloj_ini t_num;      -- primera y última habitación de cada alojamiento
    v_aloj_fin t_num;
    v_cli      t_num;
    v_dias_alta  t_fecha;
    v_dias_media t_fecha;
    v_dias_baja  t_fecha;
    v_ocupada    t_ocup;   -- noches ocupadas (habitacion_fecha)

    v_creadas    PLS_INTEGER := 0;
    v_r          NUMBER;
    v_es_alta    BOOLEAN;
    v_fecha_in   DATE;
    v_fecha_out  DATE;
    v_fecha_in2  DATE;
    v_noches     NUMBER;
    v_fecha_crea DATE;
    v_fecha_canc DATE;
    v_estado     VARCHAR2(12);
    v_idx        PLS_INTEGER;
    v_try        PLS_INTEGER;
    v_aloj       NUMBER;
    v_res_id     NUMBER;
    v_cant_aloj  PLS_INTEGER;
    v_inicio     PLS_INTEGER;
    v_extra      PLS_INTEGER;
    v_agregadas  PLS_INTEGER;
    v_j          PLS_INTEGER;
    v_id_cliente NUMBER;
    v_id_hab     NUMBER;
    v_huespedes  NUMBER;

    -- Revisa si la habitación está libre todas las noches
    FUNCTION fn_libre (p_hab NUMBER, p_in DATE, p_out DATE) RETURN BOOLEAN IS
    BEGIN
        FOR d IN 0 .. (p_out - p_in - 1) LOOP
            IF v_ocupada.EXISTS(p_hab || '_' || TO_CHAR(p_in + d, 'YYYYMMDD')) THEN
                RETURN FALSE;
            END IF;
        END LOOP;
        RETURN TRUE;
    END fn_libre;

    -- Marca las noches de la habitación como ocupadas
    PROCEDURE sp_ocupar (p_hab NUMBER, p_in DATE, p_out DATE) IS
    BEGIN
        FOR d IN 0 .. (p_out - p_in - 1) LOOP
            v_ocupada(p_hab || '_' || TO_CHAR(p_in + d, 'YYYYMMDD')) := TRUE;
        END LOOP;
    END sp_ocupar;
BEGIN
    -- Habitaciones y clientes en memoria
    SELECT id_habitacion, id_alojamiento, capacidad_max
      BULK COLLECT INTO v_hab_id, v_hab_aloj, v_hab_cap
      FROM habitacion
     ORDER BY id_alojamiento, id_habitacion;

    FOR i IN 1 .. v_hab_id.COUNT LOOP
        IF NOT v_aloj_ini.EXISTS(v_hab_aloj(i)) THEN
            v_aloj_ini(v_hab_aloj(i)) := i;
        END IF;
        v_aloj_fin(v_hab_aloj(i)) := i;
    END LOOP;

    SELECT id_cliente BULK COLLECT INTO v_cli FROM cliente;

    -- Días de cada nivel de temporada
    FOR t IN (SELECT nivel, fecha_inicio, fecha_fin FROM temporada ORDER BY fecha_inicio) LOOP
        FOR d IN 0 .. (t.fecha_fin - t.fecha_inicio) LOOP
            IF t.nivel = 'ALTA' THEN
                v_dias_alta(v_dias_alta.COUNT + 1) := t.fecha_inicio + d;
            ELSIF t.nivel = 'MEDIA' THEN
                v_dias_media(v_dias_media.COUNT + 1) := t.fecha_inicio + d;
            ELSE
                v_dias_baja(v_dias_baja.COUNT + 1) := t.fecha_inicio + d;
            END IF;
        END LOOP;
    END LOOP;

    WHILE v_creadas < 25000 LOOP
        -- Fecha de llegada según la temporada
        v_r := DBMS_RANDOM.VALUE;
        IF v_r < 0.55 THEN
            v_es_alta  := TRUE;
            v_fecha_in := v_dias_alta(TRUNC(DBMS_RANDOM.VALUE(1, v_dias_alta.COUNT + 1)));
            v_noches   := TRUNC(DBMS_RANDOM.VALUE(2, 7));       -- 2 a 6 noches
        ELSIF v_r < 0.85 THEN
            v_es_alta  := FALSE;
            v_fecha_in := v_dias_media(TRUNC(DBMS_RANDOM.VALUE(1, v_dias_media.COUNT + 1)));
            v_noches   := TRUNC(DBMS_RANDOM.VALUE(1, 5));       -- 1 a 4 noches
        ELSE
            v_es_alta  := FALSE;
            v_fecha_in := v_dias_baja(TRUNC(DBMS_RANDOM.VALUE(1, v_dias_baja.COUNT + 1)));
            v_noches   := TRUNC(DBMS_RANDOM.VALUE(1, 4));       -- 1 a 3 noches
        END IF;
        v_fecha_out := v_fecha_in + v_noches;

        -- La estadía no puede pasar del 31/12/2026
        IF v_fecha_out - 1 > c_fin THEN
            CONTINUE;
        END IF;

        -- Se busca una habitación libre (20 intentos, si no se cambia la fecha)
        v_idx := NULL;
        FOR k IN 1 .. 20 LOOP
            v_try := TRUNC(DBMS_RANDOM.VALUE(1, v_hab_id.COUNT + 1));
            IF fn_libre(v_hab_id(v_try), v_fecha_in, v_fecha_out) THEN
                v_idx := v_try;
                EXIT;
            END IF;
        END LOOP;
        IF v_idx IS NULL THEN
            CONTINUE;
        END IF;
        v_aloj := v_hab_aloj(v_idx);

        -- Fecha de creación: en alta se reserva con más anticipación
        IF v_es_alta THEN
            v_fecha_crea := v_fecha_in - TRUNC(DBMS_RANDOM.VALUE(15, 121));
        ELSE
            v_fecha_crea := v_fecha_in - TRUNC(DBMS_RANDOM.VALUE(1, 46));
        END IF;
        IF v_fecha_crea > c_corte THEN
            v_fecha_crea := c_corte - TRUNC(DBMS_RANDOM.VALUE(0, 30));
        END IF;

        -- Estado según la fecha de corte (01/10/2026)
        v_r := DBMS_RANDOM.VALUE;
        IF v_fecha_out <= c_corte THEN
            v_estado := CASE WHEN v_r < 0.86 THEN 'COMPLETADA' ELSE 'CANCELADA' END;
        ELSIF v_fecha_in < c_corte THEN
            v_estado := 'CONFIRMADA';
        ELSE
            v_estado := CASE WHEN v_r < 0.65 THEN 'CONFIRMADA'
                             WHEN v_r < 0.87 THEN 'PENDIENTE'
                             ELSE 'CANCELADA' END;
        END IF;

        -- La cancelación queda entre la creación y el check-in
        v_fecha_canc := NULL;
        IF v_estado = 'CANCELADA' THEN
            v_fecha_canc := v_fecha_crea
                            + TRUNC(DBMS_RANDOM.VALUE(0, v_fecha_in - v_fecha_crea + 1));
            IF v_fecha_canc > v_fecha_in THEN
                v_fecha_canc := v_fecha_in;
            END IF;
            IF v_fecha_canc > c_corte THEN
                v_fecha_canc := c_corte;
            END IF;
        END IF;

        -- ----------------- ENCABEZADO DE LA RESERVA ----------------------------------
        v_id_cliente := v_cli(TRUNC(DBMS_RANDOM.VALUE(1, v_cli.COUNT + 1)));

        INSERT INTO reserva (id_cliente, id_alojamiento, fecha_creacion, fecha_checkin,
                             fecha_checkout, estado, fecha_cancelacion)
        VALUES (v_id_cliente, v_aloj, v_fecha_crea,
                v_fecha_in, v_fecha_out, v_estado, v_fecha_canc)
        RETURNING id_reserva INTO v_res_id;

        -- ----------------- ASIGNACIÓN DE DETALLE EN RESERVA_HABITACION ----------------------------
        v_id_hab     := v_hab_id(v_idx);
        v_huespedes  := TRUNC(DBMS_RANDOM.VALUE(1, v_hab_cap(v_idx) + 1));

        INSERT INTO reserva_habitacion (id_reserva, id_alojamiento, id_habitacion,
                                        fecha_in, fecha_out, num_huespedes)
        VALUES (v_res_id, v_aloj, v_id_hab, v_fecha_in, v_fecha_out, v_huespedes);
        sp_ocupar(v_id_hab, v_fecha_in, v_fecha_out);

        -- Reservas de grupo: 1 o 2 habitaciones más del mismo alojamiento
        v_cant_aloj := v_aloj_fin(v_aloj) - v_aloj_ini(v_aloj) + 1;
        IF DBMS_RANDOM.VALUE < 0.10 AND v_cant_aloj > 1 THEN
            v_extra     := TRUNC(DBMS_RANDOM.VALUE(1, 3));
            v_agregadas := 0;
            v_inicio    := TRUNC(DBMS_RANDOM.VALUE(0, v_cant_aloj));

            FOR k IN 0 .. v_cant_aloj - 1 LOOP
                EXIT WHEN v_agregadas >= v_extra;
                v_j := v_aloj_ini(v_aloj) + MOD(v_inicio + k, v_cant_aloj);

                IF v_j <> v_idx THEN
                    -- A veces alguien del grupo llega un día después
                    v_fecha_in2 := v_fecha_in;
                    IF v_noches >= 2 AND DBMS_RANDOM.VALUE < 0.25 THEN
                        v_fecha_in2 := v_fecha_in + 1;
                    END IF;

                    IF fn_libre(v_hab_id(v_j), v_fecha_in2, v_fecha_out) THEN
                        v_id_hab    := v_hab_id(v_j);
                        v_huespedes := TRUNC(DBMS_RANDOM.VALUE(1, v_hab_cap(v_j) + 1));

                        INSERT INTO reserva_habitacion (id_reserva, id_alojamiento, id_habitacion,
                                                        fecha_in, fecha_out, num_huespedes)
                        VALUES (v_res_id, v_aloj, v_id_hab, v_fecha_in2, v_fecha_out, v_huespedes);
                        sp_ocupar(v_id_hab, v_fecha_in2, v_fecha_out);
                        v_agregadas := v_agregadas + 1;
                    END IF;
                END IF;
            END LOOP;
        END IF;

        v_creadas := v_creadas + 1;
        IF MOD(v_creadas, 2500) = 0 THEN
            COMMIT;
        END IF;
    END LOOP;
    COMMIT;
END;
