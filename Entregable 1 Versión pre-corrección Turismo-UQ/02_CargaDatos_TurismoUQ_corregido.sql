------------------------------ 6 - TARIFA ---------------------------------------
-- Generación de las tarifas (habitaciones x temporadas)
-- El valor cambia según el tipo de habitación, el alojamiento, las estrellas y el año.
-- Cada alojamiento sube 25 %, 50 % u 80 % en temporada alta

DECLARE
    v_base        NUMBER;
    v_f_tipo      NUMBER;
    v_f_estrellas NUMBER;
    v_f_alta      NUMBER;
    v_f_nivel     NUMBER;
    v_f_anio      NUMBER;
BEGIN
    FOR h IN (SELECT hb.id_habitacion, hb.tipo, a.id_alojamiento, a.estrellas, ta.nombre AS tipo_aloj
                FROM habitacion hb
                JOIN alojamiento a       ON a.id_alojamiento       = hb.id_alojamiento
                JOIN tipo_alojamiento ta ON ta.id_tipo_alojamiento = a.id_tipo_alojamiento) LOOP

        v_base := CASE h.tipo
                      WHEN 'SENCILLA' THEN  90000
                      WHEN 'DOBLE'    THEN 150000
                      WHEN 'SUITE'    THEN 260000
                      ELSE                 340000
                  END;

        v_f_tipo := CASE h.tipo_aloj
                        WHEN 'Hostal'         THEN 0.55
                        WHEN 'Finca Cafetera' THEN 1.00
                        WHEN 'Hotel'          THEN 1.05
                        ELSE                       1.15
                    END;

        v_f_estrellas := 0.8 + 0.1 * h.estrellas;

        v_f_alta := CASE MOD(h.id_alojamiento, 3)
                        WHEN 0 THEN 1.25
                        WHEN 1 THEN 1.50
                        ELSE        1.80
                    END;

        FOR t IN (SELECT id_temporada, nivel, EXTRACT(YEAR FROM fecha_inicio) AS anio
                    FROM temporada) LOOP

            v_f_nivel := CASE t.nivel
                             WHEN 'BAJA'  THEN 1
                             WHEN 'MEDIA' THEN 1 + (v_f_alta - 1) * 0.45
                             ELSE              v_f_alta
                         END;

            v_f_anio := CASE t.anio WHEN 2024 THEN 1.00 WHEN 2025 THEN 1.06 ELSE 1.12 END;

            INSERT INTO tarifa (id_habitacion, id_temporada, valor_noche)
            VALUES (h.id_habitacion, t.id_temporada,
                    ROUND(v_base * v_f_tipo * v_f_estrellas * v_f_nivel * v_f_anio, -3));
        END LOOP;
    END LOOP;
