-- Habitaciones por tipo de alojamiento
SELECT ta.nombre AS tipo, COUNT(DISTINCT a.id_alojamiento) AS alojamientos,
       MIN(c.hab) AS min_hab, MAX(c.hab) AS max_hab
  FROM (SELECT id_alojamiento, COUNT(*) AS hab FROM habitacion GROUP BY id_alojamiento) c
  JOIN alojamiento a       ON a.id_alojamiento       = c.id_alojamiento
  JOIN tipo_alojamiento ta ON ta.id_tipo_alojamiento = a.id_tipo_alojamiento
 GROUP BY ta.nombre;

-- Reservas por mes de llegada (estacionalidad)
SELECT TO_CHAR(fecha_checkin, 'YYYY-MM') AS mes, COUNT(*) AS reservas
  FROM reserva
 GROUP BY TO_CHAR(fecha_checkin, 'YYYY-MM')
 ORDER BY mes;

-- Reservas con más de una habitación y con más de un pago
SELECT (SELECT COUNT(*) FROM (SELECT id_reserva FROM reserva_habitacion
                               GROUP BY id_reserva HAVING COUNT(*) > 1)) AS reservas_multihabitacion,
       (SELECT COUNT(*) FROM (SELECT id_reserva FROM pago
                               GROUP BY id_reserva HAVING COUNT(*) > 1)) AS reservas_varios_pagos
  FROM dual;

-- Habitaciones con reservas cruzadas (debe dar 0)
SELECT COUNT(*) AS solapes
  FROM reserva_habitacion a
  JOIN reserva_habitacion b ON b.id_habitacion = a.id_habitacion
                           AND b.id_reserva_habitacion > a.id_reserva_habitacion
                           AND a.fecha_in < b.fecha_out
                           AND b.fecha_in < a.fecha_out;

-- Porcentaje de reservas completadas con reseña
SELECT ROUND(100 * COUNT(rs.id_resena) / NULLIF(COUNT(*), 0), 2) AS pct_con_resena
  FROM reserva r
  LEFT JOIN resena rs ON rs.id_reserva = r.id_reserva
 WHERE r.estado = 'COMPLETADA';

-- Reservas completadas donde lo pagado no cuadra con el total (debe dar 0)
WITH estadia AS (
    SELECT id_reserva, SUM(valor_noche) AS total_estadia
      FROM v_noche_ocupada
     WHERE estado = 'COMPLETADA'
     GROUP BY id_reserva
),
servicios AS (
    SELECT id_reserva, SUM(cantidad * precio_unitario) AS total_servicios
      FROM reserva_servicio
     GROUP BY id_reserva
),
pagado AS (
    SELECT id_reserva, SUM(monto) AS total_pagado
      FROM pago
     WHERE estado = 'EXITOSO'
     GROUP BY id_reserva
)
SELECT COUNT(*) AS completadas_descuadradas
  FROM reserva r
  JOIN estadia e        ON e.id_reserva = r.id_reserva
  LEFT JOIN servicios s ON s.id_reserva = r.id_reserva
  LEFT JOIN pagado p    ON p.id_reserva = r.id_reserva
 WHERE r.estado = 'COMPLETADA'
   AND e.total_estadia + NVL(s.total_servicios, 0) <> NVL(p.total_pagado, 0);
