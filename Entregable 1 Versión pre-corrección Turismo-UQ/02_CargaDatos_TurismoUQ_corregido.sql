------------------------------- 4 - HABITACION ----------------------------------
-- Carga de las habitaciones según el tipo de alojamiento
-- Hotel 30-40, finca 3-5, glamping 4-8 y hostal 6-12 habitaciones

DECLARE
    v_cantidad  NUMBER;
    v_r         NUMBER;
    v_tipo_hab  VARCHAR2(10);
    v_capacidad NUMBER;
    v_vista     VARCHAR2(40);
BEGIN
    FOR r IN (SELECT a.id_alojamiento, ta.nombre AS tipo
                FROM alojamiento a
                JOIN tipo_alojamiento ta ON ta.id_tipo_alojamiento = a.id_tipo_alojamiento
               ORDER BY a.id_alojamiento) LOOP

        v_cantidad := CASE r.tipo
                          WHEN 'Hotel'          THEN TRUNC(DBMS_RANDOM.VALUE(30, 41))
                          WHEN 'Finca Cafetera' THEN TRUNC(DBMS_RANDOM.VALUE(3, 6))
                          WHEN 'Glamping'       THEN TRUNC(DBMS_RANDOM.VALUE(4, 9))
                          ELSE                       TRUNC(DBMS_RANDOM.VALUE(6, 13))
                      END;

        FOR h IN 1 .. v_cantidad LOOP
            v_r := DBMS_RANDOM.VALUE;
            v_tipo_hab := CASE r.tipo
                              WHEN 'Hotel' THEN
                                  CASE WHEN v_r < 0.25 THEN 'SENCILLA' WHEN v_r < 0.75 THEN 'DOBLE' ELSE 'SUITE' END
                              WHEN 'Finca Cafetera' THEN
                                  CASE WHEN v_r < 0.50 THEN 'DOBLE' WHEN v_r < 0.80 THEN 'SUITE' ELSE 'CABANA' END
                              WHEN 'Glamping' THEN
                                  CASE WHEN v_r < 0.60 THEN 'CABANA' ELSE 'DOBLE' END
                              ELSE
                                  CASE WHEN v_r < 0.50 THEN 'SENCILLA' WHEN v_r < 0.80 THEN 'DOBLE' ELSE 'SUITE' END
                          END;

            v_capacidad := CASE v_tipo_hab
                               WHEN 'SENCILLA' THEN 1
                               WHEN 'DOBLE'    THEN 2
                               WHEN 'SUITE'    THEN 4
                               ELSE                 6
                           END;

            v_vista := CASE MOD(h, 3) WHEN 0 THEN 'vista al cafetal'
                                      WHEN 1 THEN 'vista a las montañas'
                                      ELSE        'vista al jardín' END;

            INSERT INTO habitacion (id_alojamiento, numero, capacidad_max, tipo, descripcion)
            VALUES (r.id_alojamiento,
                    (TRUNC((h - 1) / 10) + 1) * 100 + MOD(h - 1, 10) + 1,
                    v_capacidad,
                    v_tipo_hab,
                    'Habitación ' || LOWER(v_tipo_hab) || ' para ' || v_capacidad
                    || ' persona(s) con ' || v_vista);
        END LOOP;
    END LOOP;
    COMMIT;
END;
