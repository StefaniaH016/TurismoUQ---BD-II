------------------------------ 8 - RESERVA --------------------------------------
-- Carga de 25.000 reservas y asignación en RESERVA_HABITACION

DECLARE
    v_fecha_in     DATE;
    v_noches       NUMBER;
    v_fecha_out    DATE;
    v_fecha_crea   DATE;
    v_estado       VARCHAR2(12);
    v_fecha_canc   DATE;
    v_rand_estado  NUMBER;
    v_id_aloj      NUMBER;
    v_id_cliente   NUMBER;
    v_idx1         NUMBER;
    v_idx2         NUMBER;
    
    TYPE t_hab_rec IS RECORD (id_habitacion NUMBER, capacidad_max NUMBER);
    TYPE t_hab_list IS TABLE OF t_hab_rec;
    v_habs         t_hab_list;
    v_reserva_id   NUMBER;
BEGIN
    FOR i IN 1..25000 LOOP
        v_id_cliente := TRUNC(DBMS_RANDOM.VALUE(1, 3001));
        v_id_aloj    := TRUNC(DBMS_RANDOM.VALUE(1, 61));
        IF v_id_aloj > 60 THEN 
            v_id_aloj := 60; 
        END IF;

        SELECT id_habitacion, capacidad_max 
        BULK COLLECT INTO v_habs
        FROM habitacion 
        WHERE id_alojamiento = v_id_aloj;

        IF v_habs.COUNT = 0 THEN
            v_id_aloj := 1;
            SELECT id_habitacion, capacidad_max 
            BULK COLLECT INTO v_habs
            FROM habitacion 
            WHERE id_alojamiento = v_id_aloj;
        END IF;

        v_fecha_in   := TO_DATE('2024-01-01', 'YYYY-MM-DD') + TRUNC(DBMS_RANDOM.VALUE(0, 1050));
        v_noches     := TRUNC(DBMS_RANDOM.VALUE(1, 8));
        v_fecha_out  := v_fecha_in + v_noches;
        v_fecha_crea := v_fecha_in - TRUNC(DBMS_RANDOM.VALUE(1, 15));

        v_rand_estado := DBMS_RANDOM.VALUE;
        
        IF v_fecha_in < TO_DATE('2026-09-01', 'YYYY-MM-DD') THEN
            IF v_rand_estado < 0.82 THEN
                v_estado     := 'COMPLETADA';
                v_fecha_canc := NULL;
            ELSE
                v_estado     := 'CANCELADA';
                v_fecha_canc := v_fecha_crea;
            END IF;
        ELSE
            IF v_rand_estado < 0.60 THEN
                v_estado     := 'CONFIRMADA';
                v_fecha_canc := NULL;
            ELSIF v_rand_estado < 0.80 THEN
                v_estado     := 'PENDIENTE';
                v_fecha_canc := NULL;
            ELSE
                v_estado     := 'CANCELADA';
                v_fecha_canc := v_fecha_crea;
            END IF;
        END IF;
        
        -- ----------------- ASIGNACIÓN DE DETALLE EN RESERVA_HABITACION ----------------------------

        INSERT INTO reserva (id_cliente, id_alojamiento, fecha_creacion, fecha_checkin, fecha_checkout, estado, fecha_cancelacion)
        VALUES (v_id_cliente, v_id_aloj, v_fecha_crea, v_fecha_in, v_fecha_out, v_estado, v_fecha_canc)
        RETURNING id_reserva INTO v_reserva_id;
        
        v_idx1 := TRUNC(DBMS_RANDOM.VALUE(1, v_habs.COUNT + 1));
        IF v_idx1 > v_habs.COUNT THEN 
            v_idx1 := v_habs.COUNT; 
        END IF;

        INSERT INTO reserva_habitacion (id_reserva, id_alojamiento, id_habitacion, fecha_in, fecha_out, num_huespedes)
        VALUES (v_reserva_id, v_id_aloj, v_habs(v_idx1).id_habitacion, v_fecha_in, v_fecha_out, LEAST(2, v_habs(v_idx1).capacidad_max));

        IF i <= 2500 AND v_habs.COUNT > 1 THEN
            v_idx2 := MOD(v_idx1, v_habs.COUNT) + 1;

            INSERT INTO reserva_habitacion (id_reserva, id_alojamiento, id_habitacion, fecha_in, fecha_out, num_huespedes)
            VALUES (v_reserva_id, v_id_aloj, v_habs(v_idx2).id_habitacion, v_fecha_in, v_fecha_out, 1);
        END IF;

        IF MOD(i, 2500) = 0 THEN
            COMMIT;
        END IF;
    END LOOP;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Error en carga de reservas: ' || SQLERRM);
END;
