------------------------------ 1 - LIQUIDACION_MENSUAL --------------------------
-- Tabla donde se guarda la liquidación de cada mes por alojamiento
-- (la primera vez el DROP da error porque la tabla no existe)

DROP TABLE liquidacion_mensual;

CREATE TABLE liquidacion_mensual (
    id_liquidacion NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER NOT NULL,
    anio NUMBER(4) NOT NULL,
    mes NUMBER(2) NOT NULL,
    num_reservas NUMBER(6) NOT NULL,
    noches_vendidas NUMBER(6) NOT NULL,
    valor_estadia NUMBER(14) NOT NULL,
    valor_servicios NUMBER(14) NOT NULL,
    valor_total NUMBER(14) NOT NULL,
    fecha_liquidacion DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_liquidacion PRIMARY KEY (id_liquidacion),
    CONSTRAINT fk_liq_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
    CONSTRAINT uq_liq_aloj_mes UNIQUE (id_alojamiento, anio, mes),
    CONSTRAINT ck_liq_mes CHECK (mes BETWEEN 1 AND 12)
);

COMMENT ON TABLE liquidacion_mensual IS 'Liquidación mensual de cada alojamiento: reservas, noches, estadía y servicios.';

