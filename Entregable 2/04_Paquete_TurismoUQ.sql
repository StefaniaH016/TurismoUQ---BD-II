-- ================== CUERPO DEL PAQUETE: pkg_turismo_uq ======================

CREATE OR REPLACE PACKAGE BODY pkg_turismo_uq IS

-- ---------------------- FUNCIÓN: fn_valor_estadia ---------------------------
-- Suma noche por noche la tarifa de la temporada de cada día

    FUNCTION fn_valor_estadia (
        p_id_habitacion IN habitacion.id_habitacion%TYPE,
        p_fecha_in IN DATE,
        p_fecha_out IN DATE
    ) RETURN NUMBER IS
        v_total NUMBER := 0;
        v_noches NUMBER;
        v_fecha_noche DATE;
        v_precio_noche tarifa.valor_noche%TYPE;
    BEGIN
        v_noches := TRUNC(p_fecha_out) - TRUNC(p_fecha_in);

        IF p_fecha_in IS NULL OR p_fecha_out IS NULL OR v_noches <= 0 THEN
            RAISE_APPLICATION_ERROR(-20020, 'Fechas inválidas: el check-out debe ser mayor al check-in.');
        END IF;

        FOR i IN 0 .. v_noches - 1 LOOP
            v_fecha_noche := TRUNC(p_fecha_in) + i;

            -- Tarifa de la temporada de esa noche
            BEGIN
                SELECT tf.valor_noche
                  INTO v_precio_noche
                  FROM tarifa tf
                  JOIN temporada t ON t.id_temporada = tf.id_temporada
                 WHERE tf.id_habitacion = p_id_habitacion
                   AND v_fecha_noche BETWEEN t.fecha_inicio AND t.fecha_fin;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN
                    RAISE_APPLICATION_ERROR(-20021, 'La habitación ' || p_id_habitacion
                        || ' no tiene tarifa para el ' || TO_CHAR(v_fecha_noche, 'DD/MM/YYYY') || '.');
            END;

            v_total := v_total + v_precio_noche;
        END LOOP;

        RETURN v_total;
    END fn_valor_estadia;

-- ----------------------- PROCEDIMIENTO: sp_crear_reserva ----------------------
-- Valida fechas, cliente, capacidad y disponibilidad antes de guardar la reserva

    PROCEDURE sp_crear_reserva (
        p_id_cliente IN cliente.id_cliente%TYPE,
        p_id_alojamiento IN alojamiento.id_alojamiento%TYPE,
        p_id_habitacion IN habitacion.id_habitacion%TYPE,
        p_fecha_in IN DATE,
        p_fecha_out IN DATE,
        p_num_huespedes IN NUMBER,
        p_id_reserva OUT reserva.id_reserva%TYPE
    ) IS
        v_existe NUMBER;
        v_capacidad_max habitacion.capacidad_max%TYPE;
        v_solapes NUMBER;
        v_valor NUMBER;
    BEGIN
        -- VALIDACIÓN 1: checkout anterior o igual al checkin
        IF TRUNC(p_fecha_out) <= TRUNC(p_fecha_in) THEN
            RAISE_APPLICATION_ERROR(-20001, 'La fecha de check-out debe ser mayor a la fecha de check-in.');
        END IF;

        -- VALIDACIÓN 2: máximo 60 noches
        IF TRUNC(p_fecha_out) - TRUNC(p_fecha_in) > 60 THEN
            RAISE_APPLICATION_ERROR(-20008, 'Una habitación no se puede reservar por más de 60 noches.');
        END IF;

        -- VALIDACIÓN 3: checkin anterior a hoy
        IF TRUNC(p_fecha_in) < TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20005, 'La fecha de check-in no puede ser anterior a hoy.');
        END IF;

        -- VALIDACIÓN 4: al menos un huésped
        IF p_num_huespedes IS NULL OR p_num_huespedes < 1 THEN
            RAISE_APPLICATION_ERROR(-20007, 'La reserva debe tener al menos un huésped.');
        END IF;

        -- VALIDACIÓN 5: el cliente existe
        SELECT COUNT(*) INTO v_existe FROM cliente WHERE id_cliente = p_id_cliente;

        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20006, 'El cliente ' || p_id_cliente || ' no está registrado.');
        END IF;

        -- VALIDACIÓN 6: la habitación es de ese alojamiento
        BEGIN
            SELECT capacidad_max
              INTO v_capacidad_max
              FROM habitacion
             WHERE id_habitacion = p_id_habitacion
               AND id_alojamiento = p_id_alojamiento;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20002, 'La habitación ' || p_id_habitacion
                    || ' no pertenece al alojamiento ' || p_id_alojamiento || '.');
        END;

        -- VALIDACIÓN 7: capacidad excedida
        IF p_num_huespedes > v_capacidad_max THEN
            RAISE_APPLICATION_ERROR(-20003, 'Número de huéspedes (' || p_num_huespedes
                || ') excede la capacidad máxima de la habitación (' || v_capacidad_max || ').');
        END IF;

        -- VALIDACIÓN 8: habitación no disponible (cruce con reserva confirmada o completada)
        SELECT COUNT(*)
          INTO v_solapes
          FROM reserva_habitacion rh
          JOIN reserva r ON r.id_reserva = rh.id_reserva
         WHERE rh.id_habitacion = p_id_habitacion
           AND r.estado IN ('CONFIRMADA', 'COMPLETADA')
           AND TRUNC(p_fecha_in) < rh.fecha_out
           AND TRUNC(p_fecha_out) > rh.fecha_in;

        IF v_solapes > 0 THEN
            RAISE_APPLICATION_ERROR(-20004, 'La habitación ' || p_id_habitacion
                || ' no está disponible para el rango de fechas seleccionado.');
        END IF;

        -- VALIDACIÓN 9: todas las noches tienen tarifa (si no, la función lanza -20021)
        v_valor := fn_valor_estadia(p_id_habitacion, p_fecha_in, p_fecha_out);

        INSERT INTO reserva (id_cliente, id_alojamiento, fecha_creacion, fecha_checkin,
                             fecha_checkout, estado, fecha_cancelacion)
        VALUES (p_id_cliente, p_id_alojamiento, TRUNC(SYSDATE), TRUNC(p_fecha_in),
                TRUNC(p_fecha_out), 'CONFIRMADA', NULL)
        RETURNING id_reserva INTO p_id_reserva;

        INSERT INTO reserva_habitacion (id_reserva, id_alojamiento, id_habitacion,
                                        fecha_in, fecha_out, num_huespedes)
        VALUES (p_id_reserva, p_id_alojamiento, p_id_habitacion, TRUNC(p_fecha_in),
                TRUNC(p_fecha_out), p_num_huespedes);

        DBMS_OUTPUT.PUT_LINE('Reserva ' || p_id_reserva || ' creada. Valor de la estadía: $' || v_valor);
    END sp_crear_reserva;

-- ------------------------ CURSOR: sp_liquidacion_mensual -----------------------
-- Liquida un mes para todos los alojamientos y guarda el resultado.
-- Solo cuenta las noches que caen en el mes y los servicios del mes de llegada.

    PROCEDURE sp_liquidacion_mensual (
        p_anio IN NUMBER,
        p_mes IN NUMBER
    ) IS
        CURSOR c_alojamientos IS
            SELECT id_alojamiento, nombre
              FROM alojamiento
             ORDER BY id_alojamiento;

        -- Cursor con parámetros: habitaciones reservadas de un alojamiento en el mes
        CURSOR c_lineas (
            p_aloj alojamiento.id_alojamiento%TYPE,
            p_ini DATE,
            p_fin DATE
        ) IS
            SELECT rh.id_reserva,
                   rh.id_habitacion,
                   GREATEST(rh.fecha_in, p_ini) AS desde,
                   LEAST(rh.fecha_out, p_fin) AS hasta
              FROM reserva_habitacion rh
              JOIN reserva r ON r.id_reserva = rh.id_reserva
             WHERE r.id_alojamiento = p_aloj
               AND r.estado IN ('CONFIRMADA', 'COMPLETADA')
               AND rh.fecha_in < p_fin
               AND rh.fecha_out > p_ini
             ORDER BY rh.id_reserva;

        r_linea c_lineas%ROWTYPE;
        v_ini DATE;
        v_fin DATE;
        v_reservas NUMBER;
        v_noches NUMBER;
        v_estadia NUMBER;
        v_servicios NUMBER;
        v_ultima_reserva NUMBER;
        v_tot_aloj NUMBER := 0;
        v_tot_reservas NUMBER := 0;
        v_tot_general NUMBER := 0;
    BEGIN
        IF p_mes IS NULL OR p_mes NOT BETWEEN 1 AND 12 THEN
            RAISE_APPLICATION_ERROR(-20030, 'El mes debe estar entre 1 y 12.');
        END IF;

        -- Primer día del mes y primer día del mes siguiente
        v_ini := TO_DATE(p_anio || '-' || p_mes || '-01', 'YYYY-MM-DD');
        v_fin := ADD_MONTHS(v_ini, 1);

        -- Si el mes ya estaba liquidado se vuelve a calcular
        DELETE FROM liquidacion_mensual WHERE anio = p_anio AND mes = p_mes;

        DBMS_OUTPUT.PUT_LINE('== LIQUIDACIÓN ' || TO_CHAR(v_ini, 'YYYY-MM') || ' ==');

        FOR r_aloj IN c_alojamientos LOOP
            v_reservas := 0;
            v_noches := 0;
            v_estadia := 0;
            v_ultima_reserva := -1;

            OPEN c_lineas(r_aloj.id_alojamiento, v_ini, v_fin);
            LOOP
                FETCH c_lineas INTO r_linea;
                EXIT WHEN c_lineas%NOTFOUND;

                -- Una reserva de varias habitaciones se cuenta una vez
                IF r_linea.id_reserva <> v_ultima_reserva THEN
                    v_reservas := v_reservas + 1;
                    v_ultima_reserva := r_linea.id_reserva;
                END IF;

                v_noches := v_noches + (r_linea.hasta - r_linea.desde);
                v_estadia := v_estadia + fn_valor_estadia(r_linea.id_habitacion, r_linea.desde, r_linea.hasta);
            END LOOP;
            CLOSE c_lineas;

            SELECT NVL(SUM(rs.cantidad * rs.precio_unitario), 0)
              INTO v_servicios
              FROM reserva_servicio rs
              JOIN reserva r ON r.id_reserva = rs.id_reserva
             WHERE r.id_alojamiento = r_aloj.id_alojamiento
               AND r.estado IN ('CONFIRMADA', 'COMPLETADA')
               AND r.fecha_checkin >= v_ini
               AND r.fecha_checkin < v_fin;

            INSERT INTO liquidacion_mensual (id_alojamiento, anio, mes, num_reservas, noches_vendidas,
                                             valor_estadia, valor_servicios, valor_total)
            VALUES (r_aloj.id_alojamiento, p_anio, p_mes, v_reservas, v_noches,
                    v_estadia, v_servicios, v_estadia + v_servicios);

            DBMS_OUTPUT.PUT_LINE(r_aloj.nombre || ': ' || v_reservas || ' reservas, '
                                 || v_noches || ' noches, $' || (v_estadia + v_servicios));

            v_tot_aloj := v_tot_aloj + 1;
            v_tot_reservas := v_tot_reservas + v_reservas;
            v_tot_general := v_tot_general + v_estadia + v_servicios;
        END LOOP;

        COMMIT;

        DBMS_OUTPUT.PUT_LINE('Alojamientos liquidados: ' || v_tot_aloj);
        DBMS_OUTPUT.PUT_LINE('Total reservas: ' || v_tot_reservas || ' | Total liquidado: $' || v_tot_general);
    END sp_liquidacion_mensual;

END pkg_turismo_uq;
