
------------------------------- 1 - MUNICIPIO -----------------------------------
--Catalogo de los 12 municipios del Quindio, cada alojamiento pertenece a uno.

CREATE TABLE municipio (
    id_municipio  NUMBER        GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR2(60)  NOT NULL,
    CONSTRAINT pk_municipio        PRIMARY KEY (id_municipio),
    CONSTRAINT uq_municipio_nombre UNIQUE (nombre)
);

------------------------------- 2 - TIPO_ALOJAMIENTO ----------------------------
--Catalogo abierto de tipos de alojamiento
--(finca cafetera, hotel, glamping, hostal, apartamento turistico, etc).

CREATE TABLE tipo_alojamiento (
    id_tipo_alojamiento  NUMBER         GENERATED BY DEFAULT AS IDENTITY,
    nombre               VARCHAR2(50)   NOT NULL,
    descripcion          VARCHAR2(210),
    CONSTRAINT pk_tipo_alojamiento PRIMARY KEY (id_tipo_alojamiento),
    CONSTRAINT uq_tipo_aloj_nombre UNIQUE (nombre)
);

------------------------------- 3 - ALOJAMIENTO ---------------------------------
--Establecimiento turistico. Pertenece a un municipio y a un tipo.

CREATE TABLE alojamiento (
    id_alojamiento       NUMBER         GENERATED BY DEFAULT AS IDENTITY,
    id_municipio         NUMBER         NOT NULL,
    id_tipo_alojamiento  NUMBER         NOT NULL,
    nombre               VARCHAR2(80)  NOT NULL,
    direccion            VARCHAR2(150)  NOT NULL,
    estrellas            NUMBER(1)      NOT NULL,
    telefono             VARCHAR2(20)   NOT NULL,
    correo_contacto      VARCHAR2(120)  NOT NULL,
    CONSTRAINT pk_alojamiento     PRIMARY KEY (id_alojamiento),
    CONSTRAINT fk_aloj_municipio  FOREIGN KEY (id_municipio)        REFERENCES municipio (id_municipio),
    CONSTRAINT fk_aloj_tipo       FOREIGN KEY (id_tipo_alojamiento) REFERENCES tipo_alojamiento (id_tipo_alojamiento),
    CONSTRAINT uq_aloj_nombre     UNIQUE (id_municipio, nombre),
    CONSTRAINT ck_aloj_estrellas  CHECK (estrellas BETWEEN 1 AND 5),
    CONSTRAINT ck_aloj_correo     CHECK (correo_contacto LIKE '%@%')
);

------------------------------- 4 - HABITACION ----------------------------------
--Habitacion de un alojamiento. Dos habitaciones del mismo alojamiento no comparten numero

CREATE TABLE habitacion (
    id_habitacion   NUMBER         GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento  NUMBER         NOT NULL,
    numero          NUMBER(4)      NOT NULL,
    capacidad_max   NUMBER(2)      NOT NULL,
    tipo            VARCHAR2(10)   NOT NULL,
    descripcion     VARCHAR2(310),
    CONSTRAINT pk_habitacion      PRIMARY KEY (id_habitacion),
    CONSTRAINT fk_hab_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
    CONSTRAINT uq_hab_numero      UNIQUE (id_alojamiento, numero),
    CONSTRAINT uq_hab_aloj_id     UNIQUE (id_alojamiento, id_habitacion),
    CONSTRAINT ck_hab_numero      CHECK (numero > 0),
    CONSTRAINT ck_hab_capacidad   CHECK (capacidad_max BETWEEN 1 AND 12),
    CONSTRAINT ck_hab_tipo        CHECK (tipo IN ('SENCILLA', 'DOBLE', 'SUITE', 'CABANA'))
);


------------------------------- 5 - TEMPORADA -----------------------------------
--Almacena los rangos de fechas por año para las temporadas alta, media y baja en el 
--departamento del Quindío. Ej: Semana Santa 2026.

CREATE TABLE temporada (
    id_temporada  NUMBER         GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR2(80)   NOT NULL,
    nivel         VARCHAR2(5)    NOT NULL,
    fecha_inicio  DATE           NOT NULL,
    fecha_fin     DATE           NOT NULL,
    CONSTRAINT pk_temporada       PRIMARY KEY (id_temporada),
    CONSTRAINT uq_temporada_nombre UNIQUE (nombre),
    CONSTRAINT ck_temp_nivel      CHECK (nivel IN ('ALTA', 'MEDIA', 'BAJA')),
    CONSTRAINT ck_temp_fechas     CHECK (fecha_fin >= fecha_inicio)
);
 

------------------------------ 6 - TARIFA ---------------------------------------
--Precio por noche (COP) de una habitacion en una temporada

CREATE TABLE tarifa (
    id_tarifa      NUMBER      GENERATED BY DEFAULT AS IDENTITY,
    id_habitacion  NUMBER      NOT NULL,
    id_temporada   NUMBER      NOT NULL,
    valor_noche    NUMBER(10)  NOT NULL,
    CONSTRAINT pk_tarifa        PRIMARY KEY (id_tarifa),
    CONSTRAINT fk_tarifa_hab    FOREIGN KEY (id_habitacion) REFERENCES habitacion (id_habitacion),
    CONSTRAINT fk_tarifa_temp   FOREIGN KEY (id_temporada)  REFERENCES temporada (id_temporada),
    CONSTRAINT uq_tarifa_cruce  UNIQUE (id_habitacion, id_temporada),
    CONSTRAINT ck_tarifa_valor  CHECK (valor_noche > 0)
);


------------------------------ 7 - CLIENTE --------------------------------------
--Cliente registrado en la plataforma. El documento y el correo identifican a una unica persona.    

CREATE TABLE cliente (
    id_cliente     NUMBER         GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR2(80)  NOT NULL,
    documento      VARCHAR2(20)   NOT NULL,
    correo         VARCHAR2(120)  NOT NULL,
    telefono       VARCHAR2(20)   NOT NULL,
    ciudad_origen  VARCHAR2(55)   NOT NULL,
    CONSTRAINT pk_cliente         PRIMARY KEY (id_cliente),
    CONSTRAINT uq_cliente_doc     UNIQUE (documento),
    CONSTRAINT uq_cliente_correo  UNIQUE (correo),
    CONSTRAINT ck_cliente_correo  CHECK (correo LIKE '%@%')
);


------------------------------ 8 - RESERVA --------------------------------------
--Transacción principal que agrupa el cliente, el alojamiento y el rango de fechas globales del viaje.

CREATE TABLE reserva (
    id_reserva         NUMBER        GENERATED BY DEFAULT AS IDENTITY,
    id_cliente         NUMBER        NOT NULL,
    id_alojamiento     NUMBER        NOT NULL,
    fecha_creacion     DATE          NOT NULL,
    fecha_checkin      DATE          NOT NULL,
    fecha_checkout     DATE          NOT NULL,
    estado             VARCHAR2(12)  NOT NULL,
    fecha_cancelacion  DATE,
    CONSTRAINT pk_reserva          PRIMARY KEY (id_reserva),
    CONSTRAINT fk_res_cliente      FOREIGN KEY (id_cliente)     REFERENCES cliente (id_cliente),
    CONSTRAINT fk_res_alojamiento  FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
    CONSTRAINT uq_reserva_aloj     UNIQUE (id_reserva, id_alojamiento),
    CONSTRAINT ck_res_estado       CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA', 'COMPLETADA')),
    CONSTRAINT ck_res_fechas       CHECK (fecha_checkout > fecha_checkin),
    CONSTRAINT ck_res_max_noches   CHECK (fecha_checkout - fecha_checkin <= 90),
    CONSTRAINT ck_res_creacion     CHECK (fecha_creacion <= fecha_checkin),
    CONSTRAINT ck_res_cancelacion  CHECK (
        (estado = 'CANCELADA' AND fecha_cancelacion IS NOT NULL
                              AND fecha_cancelacion >= fecha_creacion
                              AND fecha_cancelacion <= fecha_checkin)
        OR
        (estado <> 'CANCELADA' AND fecha_cancelacion IS NULL)
    )
);

------------------------------- 9 - RESERVA_HABITACION --------------------------
-- Detalle de las habitaciones asignadas a una reserva, incluyendo sus fechas particulares y número de huéspedes.

CREATE TABLE reserva_habitacion (
    id_reserva_habitacion  NUMBER      GENERATED BY DEFAULT AS IDENTITY,
    id_reserva             NUMBER      NOT NULL,
    id_alojamiento         NUMBER      NOT NULL,
    id_habitacion          NUMBER      NOT NULL,
    fecha_in               DATE        NOT NULL,
    fecha_out              DATE        NOT NULL,
    num_huespedes          NUMBER(2)   NOT NULL,
    CONSTRAINT pk_reserva_habitacion  PRIMARY KEY (id_reserva_habitacion),
    CONSTRAINT fk_rh_reserva          FOREIGN KEY (id_reserva, id_alojamiento)
                                      REFERENCES reserva (id_reserva, id_alojamiento),
    CONSTRAINT fk_rh_habitacion       FOREIGN KEY (id_alojamiento, id_habitacion)
                                      REFERENCES habitacion (id_alojamiento, id_habitacion),
    CONSTRAINT uq_rh_reserva_hab      UNIQUE (id_reserva, id_habitacion),
    CONSTRAINT ck_rh_fechas           CHECK (fecha_out > fecha_in),
    CONSTRAINT ck_rh_max_noches       CHECK (fecha_out - fecha_in <= 60),
    CONSTRAINT ck_rh_huespedes        CHECK (num_huespedes >= 1)
);

------------------------------ 10 - PAGO ----------------------------------------
--Registro de los abonos e transacciones financieras asociadas a una reserva.

CREATE TABLE pago (
    id_pago     NUMBER        GENERATED BY DEFAULT AS IDENTITY,
    id_reserva  NUMBER        NOT NULL,
    fecha_pago  DATE          NOT NULL,
    monto       NUMBER(12)    NOT NULL,
    metodo      VARCHAR2(20)  NOT NULL,
    estado      VARCHAR2(12)  NOT NULL,
    CONSTRAINT pk_pago         PRIMARY KEY (id_pago),
    CONSTRAINT fk_pago_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
    CONSTRAINT ck_pago_monto   CHECK (monto > 0),
    CONSTRAINT ck_pago_metodo  CHECK (metodo IN ('TARJETA_CREDITO', 'TARJETA_DEBITO', 'PSE', 'TRANSFERENCIA', 'EFECTIVO')),
    CONSTRAINT ck_pago_estado  CHECK (estado IN ('EXITOSO', 'FALLIDO', 'PENDIENTE', 'REEMBOLSADO'))
);

------------------------------ 11 - SERVICIO ------------------------------------
--Catálogo de servicios adicionales ofertados por cada alojamiento específico (desayunos, tours, spa, etc).

CREATE TABLE servicio (
    id_servicio     NUMBER         GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento  NUMBER         NOT NULL,
    nombre          VARCHAR2(80)   NOT NULL,
    descripcion     VARCHAR2(310),
    precio          NUMBER(10)     NOT NULL,
    CONSTRAINT pk_servicio         PRIMARY KEY (id_servicio),
    CONSTRAINT fk_serv_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
    CONSTRAINT uq_serv_nombre      UNIQUE (id_alojamiento, nombre),
    CONSTRAINT uq_serv_aloj_id     UNIQUE (id_alojamiento, id_servicio),
    CONSTRAINT ck_serv_precio      CHECK (precio >= 0)
);


------------------------------ 12 - RESERVA_SERVICIO ----------------------------
--Detalle de los servicios contratados dentro de una reserva, congelando la cantidad y el precio unitario del momento.

CREATE TABLE reserva_servicio (
    id_reserva_servicio  NUMBER      GENERATED BY DEFAULT AS IDENTITY,
    id_reserva           NUMBER      NOT NULL,
    id_alojamiento       NUMBER      NOT NULL,
    id_servicio          NUMBER      NOT NULL,
    cantidad             NUMBER(3)   NOT NULL,
    precio_unitario      NUMBER(10)  NOT NULL,
    CONSTRAINT pk_reserva_servicio  PRIMARY KEY (id_reserva_servicio),
    CONSTRAINT fk_rs_reserva        FOREIGN KEY (id_reserva, id_alojamiento)
                                    REFERENCES reserva (id_reserva, id_alojamiento),
    CONSTRAINT fk_rs_servicio       FOREIGN KEY (id_alojamiento, id_servicio)
                                    REFERENCES servicio (id_alojamiento, id_servicio),
    CONSTRAINT uq_rs_reserva_serv   UNIQUE (id_reserva, id_servicio),
    CONSTRAINT ck_rs_cantidad       CHECK (cantidad >= 1),
    CONSTRAINT ck_rs_precio         CHECK (precio_unitario >= 0)
);

---------------------------- 13 - RESEÑA ----------------------------------------
--Evaluaciones y comentarios de los clientes sobre alojamientos tras completar sus estadias.

CREATE TABLE resena (
    id_resena     NUMBER         GENERATED BY DEFAULT AS IDENTITY,
    id_reserva    NUMBER         NOT NULL,
    calificacion  NUMBER(1)      NOT NULL,
    comentario    VARCHAR2(800),
    fecha_resena  DATE           NOT NULL,
    CONSTRAINT pk_resena          PRIMARY KEY (id_resena),
    CONSTRAINT fk_resena_reserva  FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
    CONSTRAINT uq_resena_reserva  UNIQUE (id_reserva),
    CONSTRAINT ck_resena_calif    CHECK (calificacion BETWEEN 1 AND 5)
);

---------------------------- 14 - USUARIO_SISTEMA -------------------------------
--Cuentas del personal interno con permisos globales (ADMIN) o restringidos a un hospedaje (ENCARGADO).

CREATE TABLE usuario_sistema (
    id_usuario      NUMBER         GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(60)  NOT NULL,
    correo          VARCHAR2(120)  NOT NULL,
    rol             VARCHAR2(10)   NOT NULL,
    id_alojamiento  NUMBER,
    CONSTRAINT pk_usuario_sistema  PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_correo   UNIQUE (correo),
    CONSTRAINT fk_usuario_aloj     FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
    CONSTRAINT ck_usuario_rol      CHECK (rol IN ('ADMIN', 'ENCARGADO')),
    CONSTRAINT ck_usuario_aloj     CHECK (
        (rol = 'ADMIN'     AND id_alojamiento IS NULL) OR
        (rol = 'ENCARGADO' AND id_alojamiento IS NOT NULL)
    )
);

--------------------------- 15 - VISTA V_NOCHE_OCUPADA --------------------------
--Desglose diario por habitación ocupada, indicando la fecha exacta, temporada y precio aplicable por noche.

CREATE OR REPLACE VIEW v_noche_ocupada AS
SELECT rh.id_reserva_habitacion,
       rh.id_reserva,
       r.id_alojamiento,
       rh.id_habitacion,
       r.estado,
       CAST(rh.fecha_in + s.n AS DATE) AS fecha_noche,
       t.id_temporada,
       t.nivel,
       tf.valor_noche
FROM   reserva_habitacion rh
JOIN   reserva  r  ON r.id_reserva = rh.id_reserva
JOIN   (SELECT LEVEL - 1 AS n FROM dual CONNECT BY LEVEL <= 90) s
                   ON s.n < rh.fecha_out - rh.fecha_in
JOIN   temporada t ON rh.fecha_in + s.n BETWEEN t.fecha_inicio AND t.fecha_fin
JOIN   tarifa   tf ON tf.id_habitacion = rh.id_habitacion
                  AND tf.id_temporada  = t.id_temporada
WHERE  r.estado IN ('CONFIRMADA', 'COMPLETADA');                 
